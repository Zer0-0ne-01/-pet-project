# Импортируем библиотеку Pygame. Без этого мы не сможем ничего нарисовать.
import pygame

# Инициализируем все модули Pygame (графика, звук, шрифты и т.д.).
# ЭТО ОБЯЗАТЕЛЬНО делать до создания окна.
pygame.init()

# Создаём окно игры.
# pygame.display.set_mode((ширина, высота)) возвращает объект Surface —
# это "холст", на котором мы будем рисовать всё, что видит игрок.
WIDTH, HEIGHT = 1024, 768
screen = pygame.display.set_mode((WIDTH, HEIGHT))

# Устанавливаем заголовок окна (текст в верхней панели).
pygame.display.set_caption("Моя первая игра на Pygame")

# Создаём объект Clock для управления частотой кадров (FPS).
# Он нужен, чтобы игра не "съедала" 100% процессора и работала одинаково
# на быстрых и медленных компьютерах.
clock = pygame.time.Clock()

# Флаг, который управляет игровым циклом.
# Пока running == True — игра работает. Как только станет False — цикл прервётся и игра закроется.
running = True

# ================== ОСНОВНОЙ ИГРОВОЙ ЦИКЛ ==================
# Игровой цикл — это сердце любой игры.
# Он повторяется десятки раз в секунду и на каждом "кадре" делает три вещи:
#   1. Обрабатывает события (нажатия клавиш, клики мыши, закрытие окна).
#   2. Обновляет логику игры (движение объектов, физика, счёт и т.д.).
#   3. Рисует новое состояние экрана.
while running:

    # --- БЛОК 1: ОБРАБОТКА СОБЫТИЙ ---
    # pygame.event.get() возвращает список всех событий, которые произошли
    # с момента прошлого кадра (например, нажатия клавиш или клики).
    for event in pygame.event.get():

        # Если игрок нажал на крестик в углу окна — выходим из цикла.
        if event.type == pygame.QUIT:
            running = False

        # Обрабатываем нажатия клавиш клавиатуры.
        elif event.type == pygame.KEYDOWN:
            # Если нажата клавиша Esc — тоже выходим из игры.
            if event.key == pygame.K_ESCAPE:
                running = False

    # --- БЛОК 2: ОБНОВЛЕНИЕ ЛОГИКИ ---
    # Здесь в будущем будет движение персонажа, столкновения, счёт и т.п.
    # В этом минимальном примере обновлять нечего.

    # --- БЛОК 3: РИСОВАНИЕ ---
    # Заливаем весь экран тёмно-синим цветом.
    # Цвет задаётся кортежем (R, G, B), каждое значение от 0 до 255.
    # (0, 0, 100) — это тёмно-синий.
    screen.fill((0, 0, 100))

    # Показываем нарисованное на экране.
    # Без этой строки мы бы рисовали "в буфере", но игрок ничего не увидел бы.
    pygame.display.flip()

    # Ограничиваем игру 60 кадрами в секунду.
    # Это делает движение плавным и предсказуемым.
    clock.tick(60)

# Когда игровой цикл завершился — корректно выключаем Pygame.
pygame.quit()